#!/usr/bin/env node
/* =====================================================================
   build-public-catalog.js — makes the public product list for the website
   from the inventory app's catalogue (gazishoaib33/unique-traders).

   Usage (from this repo's root, with the inventory repo checked out
   next to it):
     node tools/build-public-catalog.js ../unique-traders

   Writes:
     catalog-data.js                — public fields ONLY (see PUBLIC FIELDS)
     images/products/catalog/*.jpg  — product photos resized for the web
                                      (needs ImageMagick's `convert`)

   PUBLIC FIELDS: product name, product code (SKU), category, brand,
   size/description, photo, and variant names (e.g. Left/Right Hand).
   Cost price, selling price, stock and barcodes are NEVER copied — the
   website asks visitors to message for the price.
   ===================================================================== */
"use strict";
const fs = require("fs");
const path = require("path");
const vm = require("vm");
const { execFileSync } = require("child_process");

const inventoryRoot = path.resolve(process.argv[2] || "../unique-traders");
const siteRoot = path.resolve(__dirname, "..");
const sourceFile = path.join(inventoryRoot, "js", "real-catalog-data.js");
if (!fs.existsSync(sourceFile)) {
  console.error(`Catalogue not found: ${sourceFile}\nPass the path to the unique-traders repo.`);
  process.exit(1);
}

const sandbox = { window: {} };
vm.runInNewContext(fs.readFileSync(sourceFile, "utf8"), sandbox);
const source = sandbox.window.REAL_CATALOG;

// Bangla labels for the catalogue's categories (English name kept too).
const CATEGORY_BN = {
  "Cabinet": "ক্যাবিনেট",
  "Cat Door": "ক্যাট ডোর",
  "Decorative Flush": "ডেকোরেটিভ ফ্লাশ ডোর",
  "Fire Door": "ফায়ার ডোর",
  "Flush Shutter": "ফ্লাশ শাটার",
  "Formica flush Shutter": "ফরমিকা ফ্লাশ শাটার",
  "Frame": "ফ্রেম",
  "Glass Door": "গ্লাস ডোর",
  "PVC Door": "পিভিসি ডোর",
  "Popular Metal Door": "পপুলার মেটাল ডোর",
  "Premier Metal Door": "প্রিমিয়ার মেটাল ডোর",
  "Screw": "স্ক্রু",
  "Wooden Shutter": "কাঠের শাটার",
};

const imageDir = path.join(siteRoot, "images", "products", "catalog");
fs.mkdirSync(imageDir, { recursive: true });

function webImage(imageUrl) {
  if (!imageUrl) return "";
  const src = path.join(inventoryRoot, imageUrl);
  if (!fs.existsSync(src)) return "";
  const out = path.basename(imageUrl).replace(/\.[^.]+$/, "") + ".jpg";
  const dest = path.join(imageDir, out);
  if (!fs.existsSync(dest)) {
    // Max 640px, white background for transparent PNGs, stripped metadata.
    execFileSync("convert", [src, "-background", "white", "-alpha", "remove", "-resize", "640x640>", "-strip", "-quality", "78", dest]);
  }
  return `images/products/catalog/${out}`;
}

const tidy = (s) => String(s || "").replace(/\s*\.\s*$/, "").replace(/\s+/g, " ").trim();

const categories = source.categories.map((c) => ({ id: c.id, name: c.name, nameBn: CATEGORY_BN[c.name] || c.name }));
const products = source.products.map((p) => ({
  // Whitelist — only these fields are published.
  name: tidy(p.name),
  sku: p.sku,
  category: p.categoryId,
  brand: p.brand || "",
  size: tidy(p.description),
  image: webImage(p.imageUrl),
  variants: p.hasVariants ? p.variants.map((v) => ({ name: v.name, sku: v.sku })) : [],
}));

const out = `/* Generated by tools/build-public-catalog.js — do not edit by hand.
   Public product list: names, sizes, variants and photos only.
   Prices, costs and stock are intentionally NOT included. */
window.UT_CATALOG = ${JSON.stringify({ categories, products }, null, 1)};
`;
fs.writeFileSync(path.join(siteRoot, "catalog-data.js"), out);
console.log(`Wrote ${products.length} products in ${categories.length} categories; ${products.filter((p) => p.image).length} with photos.`);
